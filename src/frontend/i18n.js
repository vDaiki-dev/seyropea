export const DICTIONARIES = { es: ES, en: EN, pt: PT, hi: HI, ru: RU, zh: ZH, fr: FR, de: DE, ja: JA, ar: AR };

export class I18n {
  constructor(editor) {
    this.editor = editor;
    const saved = editor.settings?.language || 'es';
    this.locale = DICTIONARIES[saved] ? saved : 'es';
    this.applyDocumentLang();
  }

  applyDocumentLang() {
    if (typeof document !== 'undefined') document.documentElement.lang = this.locale;
  }

  t(key, fallback = '') {
    const value = DICTIONARIES[this.locale]?.[key] ?? ES[key] ?? fallback;
    return String(value);
  }

  localeList() {
    return SUPPORTED_LOCALES.map((l) => ({ ...l }));
  }

  async setLocale(locale, persist = true) {
    const next = DICTIONARIES[locale] ? locale : 'es';
    this.locale = next;
    this.editor.settings.language = next;
    this.applyDocumentLang();
    this.editor.ui?.applyI18n?.();
    if (persist) this.editor.persistSettings?.();
    try { await api.setMenuLocale(next); } catch { /* menú opcional fuera del entorno Tauri */ }
    return next;
  }
}

export default I18n;
